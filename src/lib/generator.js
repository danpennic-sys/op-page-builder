const DEFAULT_ACCENT = '#c8691e';

export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Returns a normalized URL string for http, https or mailto, else null. */
export function safeUrl(value) {
  try {
    const url = new URL(String(value ?? '').trim());
    return ['http:', 'https:', 'mailto:'].includes(url.protocol) ? url.href : null;
  } catch {
    return null;
  }
}

export function normalizeForm(form = {}) {
  const features = (Array.isArray(form.features) ? form.features : String(form.features ?? '').split('\n'))
    .map((f) => String(f).trim())
    .filter(Boolean)
    .slice(0, 6);
  const accent = /^#[0-9a-fA-F]{6}$/.test(form.accentColor ?? '') ? form.accentColor : DEFAULT_ACCENT;
  return {
    businessName: String(form.businessName ?? '').trim(),
    headline: String(form.headline ?? '').trim(),
    subheadline: String(form.subheadline ?? '').trim(),
    ctaText: String(form.ctaText ?? '').trim() || 'Get in touch',
    ctaUrl: String(form.ctaUrl ?? '').trim(),
    contactEmail: String(form.contactEmail ?? '').trim(),
    features,
    accent,
  };
}

/**
 * Generate a standalone HTML landing page. Pure function, no I/O, no network.
 * Throws an Error listing every problem if the form is invalid.
 */
export function generatePage(form, { date = new Date().toISOString().slice(0, 10) } = {}) {
  const f = normalizeForm(form);
  const problems = [];
  if (!f.businessName) problems.push('businessName is required');
  if (!f.headline) problems.push('headline is required');
  let ctaHref = null;
  if (f.ctaUrl) {
    ctaHref = safeUrl(f.ctaUrl);
    if (!ctaHref) problems.push('ctaUrl must be an http, https or mailto URL');
  } else if (f.contactEmail) {
    ctaHref = safeUrl(`mailto:${f.contactEmail}`);
    if (!ctaHref || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(f.contactEmail)) {
      ctaHref = null;
      problems.push('contactEmail is not a valid email address');
    }
  }
  if (problems.length) throw new Error(problems.join('; '));

  const e = escapeHtml;
  const cta = ctaHref
    ? `<a class="cta" href="${e(ctaHref)}" rel="noopener noreferrer">${e(f.ctaText)}</a>`
    : '';
  const featureList = f.features.length
    ? `<section aria-label="Features"><ul class="features">\n${f.features
        .map((t) => `      <li>${e(t)}</li>`)
        .join('\n')}\n    </ul></section>`
    : '';

  return `<!DOCTYPE html>
<!--
  Generated by op-page-builder
  Date: ${e(date)}
  Copyright (c) ${e(date.slice(0, 4))} Operator Pages LLC. All rights reserved.
  Operator-approved export only. Not verified or published automatically.
-->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${e(f.businessName)}</title>
  <style>
    :root { --accent: ${f.accent}; --bg: #14110f; --fg: #f2ece4; --muted: #b8aea2; }
    * { box-sizing: border-box; }
    body { margin: 0; font-family: system-ui, sans-serif; background: var(--bg); color: var(--fg); line-height: 1.5; }
    main { max-width: 40rem; margin: 0 auto; padding: 3rem 1.25rem; }
    .brand { color: var(--accent); font-weight: 700; letter-spacing: .08em; text-transform: uppercase; font-size: .85rem; }
    h1 { font-size: clamp(2rem, 8vw, 3rem); line-height: 1.1; margin: .75rem 0; }
    .sub { color: var(--muted); font-size: 1.15rem; }
    .cta { display: inline-block; margin-top: 1.5rem; padding: .9rem 1.5rem; background: var(--accent); color: #14110f; font-weight: 700; border-radius: .5rem; text-decoration: none; }
    .features { list-style: none; padding: 0; margin: 2.5rem 0 0; display: grid; gap: .75rem; }
    .features li { padding: 1rem; border: 1px solid #3a322b; border-radius: .5rem; }
    footer { margin-top: 3rem; color: var(--muted); font-size: .85rem; }
  </style>
</head>
<body>
  <main>
    <div class="brand">${e(f.businessName)}</div>
    <h1>${e(f.headline)}</h1>
    ${f.subheadline ? `<p class="sub">${e(f.subheadline)}</p>` : ''}
    ${cta}
    ${featureList}
    <footer>&copy; ${e(date.slice(0, 4))} ${e(f.businessName)}</footer>
  </main>
</body>
</html>
`;
}
